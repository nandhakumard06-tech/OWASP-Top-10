import { useMemo, useState } from 'react';
import { Check, Copy } from 'lucide-react';

import { highlight, languageLabels, normaliseLanguage } from './prism';
import { RichText } from '@/components/ui/RichText';
import { cn } from '@/utils/cn';

interface CodeBlockProps {
  code: string;
  language: string;
  filename?: string;
  /** 1-based line numbers to flag. */
  markedLines?: number[];
  /** `danger` marks vulnerable lines, `success` marks corrected lines. */
  markerTone?: 'danger' | 'success';
  /** 1-based line number -> explanation shown below the code. */
  annotations?: Record<number, string>;
  className?: string;
  /** Compact mode hides the copy button and reduces padding. */
  compact?: boolean;
  ariaLabel?: string;
}

/**
 * Syntax-highlighted code panel with optional per-line markers and
 * line-by-line annotations. Rendered from static lesson data only.
 */
export function CodeBlock({
  code,
  language,
  filename,
  markedLines,
  markerTone = 'danger',
  annotations,
  className,
  compact,
  ariaLabel,
}: CodeBlockProps) {
  const [copied, setCopied] = useState(false);
  const lines = useMemo(() => code.replace(/\s+$/, '').split('\n'), [code]);
  const marked = useMemo(() => new Set(markedLines ?? []), [markedLines]);
  const lang = normaliseLanguage(language);

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(code);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1600);
    } catch {
      // Clipboard access can be denied; the code remains selectable by hand.
      setCopied(false);
    }
  };

  const annotationEntries = useMemo(() => {
    if (!annotations) return [];
    return Object.entries(annotations)
      .map(([line, text]) => ({ line: Number(line), text }))
      .filter((entry) => Number.isFinite(entry.line))
      .sort((a, b) => a.line - b.line);
  }, [annotations]);

  return (
    <figure className={cn('flex min-w-0 flex-col', className)}>
      <div className="flex items-center justify-between gap-2 rounded-t-xl border border-b-0 border-[var(--osa-border)] bg-[var(--osa-bg-secondary)] px-3 py-2">
        <div className="flex min-w-0 items-center gap-2">
          <span
            aria-hidden="true"
            className={cn(
              'size-2 shrink-0 rounded-full',
              markerTone === 'danger' ? 'bg-[var(--osa-critical)]' : 'bg-[var(--osa-accent)]',
            )}
          />
          <figcaption className="truncate font-mono text-xs text-[var(--osa-muted)]">
            {filename ?? languageLabels[lang] ?? lang}
          </figcaption>
        </div>
        <div className="flex items-center gap-2">
          <span className="hidden rounded border border-[var(--osa-border)] px-1.5 py-0.5 font-mono text-[10px] uppercase tracking-wide text-[var(--osa-muted)] sm:inline">
            {lang}
          </span>
          {compact ? null : (
            <button
              type="button"
              onClick={handleCopy}
              aria-label={copied ? 'Code copied' : 'Copy code to clipboard'}
              className="inline-flex items-center gap-1 rounded-lg px-2 py-1 text-xs text-[var(--osa-muted)] hover:bg-[var(--osa-hover)] hover:text-[var(--osa-text)]"
            >
              {copied ? (
                <Check aria-hidden="true" className="size-3.5 text-[var(--osa-accent)]" />
              ) : (
                <Copy aria-hidden="true" className="size-3.5" />
              )}
              <span aria-live="polite">{copied ? 'Copied' : 'Copy'}</span>
            </button>
          )}
        </div>
      </div>

      <div
        className={cn(
          'min-w-0 overflow-x-auto rounded-b-xl border border-[var(--osa-border)] bg-[var(--osa-card)] font-mono text-[12.5px] leading-6',
          compact ? 'py-2' : 'py-3',
        )}
      >
        <pre
          className={cn('m-0 min-w-full', `language-${lang}`)}
          aria-label={ariaLabel ?? `${filename ?? lang} code sample`}
        >
          <code className={`language-${lang}`}>
            {lines.map((line, index) => {
              const lineNumber = index + 1;
              const isMarked = marked.has(lineNumber);
              return (
                <span
                  key={`${lineNumber}-${line.slice(0, 12)}`}
                  className="osa-code-line"
                  data-vulnerable={markerTone === 'danger' && isMarked ? 'true' : undefined}
                  data-highlight={markerTone === 'success' && isMarked ? 'true' : undefined}
                >
                  <span className="osa-line-number" aria-hidden="true">
                    {lineNumber}
                  </span>
                  <span
                    className="whitespace-pre"
                    // Highlighted output is generated by Prism from static lesson strings.
                    dangerouslySetInnerHTML={{ __html: highlight(line, lang) || '&nbsp;' }}
                  />
                </span>
              );
            })}
          </code>
        </pre>
      </div>

      {annotationEntries.length > 0 ? (
        <ul className="mt-2 flex flex-col gap-1.5">
          {annotationEntries.map((entry) => (
            <li key={entry.line} className="flex gap-2 text-xs leading-relaxed text-[var(--osa-muted)]">
              <span
                className={cn(
                  'mt-0.5 h-fit shrink-0 rounded border px-1.5 py-0.5 font-mono text-[10px] tabular-nums',
                  markerTone === 'danger'
                    ? 'border-[color-mix(in_srgb,var(--osa-critical)_45%,transparent)] text-[var(--osa-critical)]'
                    : 'border-[color-mix(in_srgb,var(--osa-accent)_45%,transparent)] text-[var(--osa-accent)]',
                )}
              >
                line {entry.line}
              </span>
              <RichText text={entry.text} />
            </li>
          ))}
        </ul>
      ) : null}
    </figure>
  );
}
